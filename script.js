const duasContainer = document.getElementById("duasContainer");


/* =========================================================
   FAVORITES
   ========================================================= */

let favorites = JSON.parse(
    localStorage.getItem("favoriteDuas")
) || [];


function isFavorite(number) {
    return favorites.includes(number);
}


function toggleFavorite(number) {

    if (isFavorite(number)) {

        favorites = favorites.filter(
            item => item !== number
        );

    } else {

        favorites.push(number);

    }

    localStorage.setItem(
        "favoriteDuas",
        JSON.stringify(favorites)
    );

    displayDuas(duas);
}


/* =========================================================
   DISPLAY DUAS
   ========================================================= */

function displayDuas(list) {

    if (!duasContainer) {
        console.error("duasContainer was not found in index.html.");
        return;
    }

    duasContainer.innerHTML = "";

    list.forEach(function (dua) {

        const card = document.createElement("div");

        card.className = "dua-card";


        /* Favorite button */

        const favoriteButton = document.createElement("button");

        favoriteButton.className =
            isFavorite(dua.number)
                ? "favorite active"
                : "favorite";

        favoriteButton.setAttribute(
            "aria-label",
            "Favorite Dua"
        );

        favoriteButton.setAttribute(
            "title",
            "Favorite Dua"
        );

        favoriteButton.textContent =
            isFavorite(dua.number)
                ? "♥"
                : "♡";


        favoriteButton.addEventListener(
            "click",
            function (event) {

                event.stopPropagation();

                toggleFavorite(dua.number);

            }
        );


        /* Dua number */

        const number = document.createElement("div");

        number.className = "dua-number";

        number.textContent = "DUA " + dua.number;


        /* Title */

        const title = document.createElement("h3");

        title.className = "dua-title";

        title.textContent = dua.title;


        /* Arabic */

        const arabic = document.createElement("div");

        arabic.className = "dua-arabic";

        arabic.textContent = dua.arabic;


        /* Transliteration */

        const transliteration =
            document.createElement("p");

        transliteration.className =
            "dua-transliteration";

        transliteration.textContent =
            dua.transliteration;


        /* Meaning */

        const meaning =
            document.createElement("p");

        meaning.className = "dua-meaning";

        meaning.textContent = dua.meaning;


        /* Reference */

        const reference =
            document.createElement("div");

        reference.className = "dua-reference";

        reference.textContent =
            "Qur'an — " + dua.reference;


        /* Add everything to card */

        card.appendChild(favoriteButton);
        card.appendChild(number);
        card.appendChild(title);
        card.appendChild(arabic);
        card.appendChild(transliteration);
        card.appendChild(meaning);
        card.appendChild(reference);


        /* Whole card opens popup */

        card.addEventListener(
            "click",
            function () {

                openDua(dua.number);

            }
        );


        duasContainer.appendChild(card);

    });
}


/* =========================================================
   INITIAL DISPLAY
   ========================================================= */

displayDuas(duas);


/* =========================================================
   OPEN DUA POPUP
   ========================================================= */

function openDua(number) {

    const dua = duas.find(
        function (item) {
            return item.number === number;
        }
    );

    if (!dua) {
        return;
    }


    /* Remove existing popup */

    const existingPopup =
        document.querySelector(".dua-popup");

    if (existingPopup) {
        existingPopup.remove();
    }


    /* Create popup */

    const popup =
        document.createElement("div");

    popup.className = "dua-popup";


    /* Popup content */

    popup.innerHTML = `

        <div class="popup-content">

            <button
                class="close-popup"
                type="button"
                aria-label="Close">
                ×
            </button>

            <div class="popup-number">
                DUA ${dua.number}
            </div>

            <h2>
                ${dua.title}
            </h2>

            <div class="popup-arabic">
                ${dua.arabic}
            </div>

            <p class="popup-transliteration">
                ${dua.transliteration}
            </p>

            <div class="popup-meaning">

                <strong>
                    Meaning
                </strong>

                <p>
                    ${dua.meaning}
                </p>

            </div>

            <div class="popup-reference">
                Qur'an — ${dua.reference}
            </div>

            <button
                class="copy-dua-btn"
                type="button">
                📋 Copy Dua
            </button>

        </div>

    `;


    /* Close button */

    popup.querySelector(".close-popup")
        .addEventListener(
            "click",
            function () {

                closeDua();

            }
        );


    /* Copy button */

    popup.querySelector(".copy-dua-btn")
        .addEventListener(
            "click",
            function () {

                copyDua(dua.number);

            }
        );


    /* Add popup */

    document.body.appendChild(popup);

    document.body.style.overflow = "hidden";
}


/* =========================================================
   CLOSE DUA POPUP
   ========================================================= */

function closeDua() {

    const popup =
        document.querySelector(".dua-popup");

    if (popup) {
        popup.remove();
    }

    document.body.style.overflow = "";
}


/* =========================================================
   COPY DUA
   ========================================================= */

function copyDua(number) {

    const dua = duas.find(
        function (item) {
            return item.number === number;
        }
    );

    if (!dua) {
        return;
    }


    const text =
`${dua.title}

${dua.arabic}

${dua.transliteration}

${dua.meaning}

Qur'an — ${dua.reference}`;


    navigator.clipboard.writeText(text)
        .then(function () {

            alert("Dua copied successfully 🤍");

        })
        .catch(function () {

            alert("Unable to copy the dua.");

        });
}


/* =========================================================
   ESCAPE KEY
   ========================================================= */

document.addEventListener(
    "keydown",
    function (event) {

        if (event.key === "Escape") {

            closeDua();

        }

    }
);